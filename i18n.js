// Language: the visitor's saved choice → the browser's languages (uk / ru / en) → Ukrainian
function detectLang() {
  try {
    const saved = localStorage.getItem('dbcp_lang');
    if (saved && I18N[saved]) return saved;
  } catch { /* storage unavailable */ }
  const prefs = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || ''])
    .map((l) => String(l).toLowerCase().slice(0, 2));
  for (const l of prefs) {
    if (l === 'uk' || l === 'ru' || l === 'en') return l;
    if (l === 'be') return 'ru';
  }
  return DEFAULT_LANG;
}
let LANG = detectLang();

function t(key, vars) {
  let s = I18N[LANG][key];
  if (s == null) s = I18N.en[key];
  if (s == null) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
  return s;
}

// { en, ru, uk } → current language (falls back to English)
const L = (obj) => (obj ? obj[LANG] || obj.en || '' : '');

function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  const desc = document.querySelector('meta[name="description"]');
  if (desc) desc.content = t('meta.description');
}

function saveLang(lang) {
  if (!I18N[lang]) return;
  LANG = lang;
  try { localStorage.setItem('dbcp_lang', lang); } catch { /* ignore */ }
}
